import type { BrandGlyph } from '@/components/icons/brand-glyphs';

/**
 * Franchise / merchant brand registry — powers merchant avatars.
 *
 * Each brand is drawn either from its real logo glyph (Simple Icons, CC0 —
 * see brand-glyphs.ts) or, for the many Korean chains Simple Icons lacks, as
 * a brand-colored wordmark badge in the same language as CardIcon/BankIcon.
 *
 * Matching runs on card-statement style names too ("비지에프리테일" is CU,
 * "우아한형제들" is 배민), so string matchers include the operating company.
 * Order matters: specific names come before generic ones (이마트24 before
 * 이마트, 쿠팡이츠 before 쿠팡). String matchers are tested against a
 * normalized name (lowercase, no spaces/punctuation); RegExp matchers against
 * the lowercased raw name, for short tokens that need word boundaries.
 */

export type Brand = {
  id: string;
  name: string;
  /** CSS background (color or gradient). */
  bg: string;
  /** Wordmark / glyph color. */
  fg: string;
  /** Wordmark when there's no glyph. */
  label?: string;
  glyph?: BrandGlyph;
  /** Fraction of the circle the glyph spans (default 0.56). */
  glyphScale?: number;
  /** Hairline ring for light backgrounds. */
  ring?: boolean;
  /** Default category — feeds category suggestions for new merchants. */
  cat?: string;
  match: Array<string | RegExp>;
};

