function normalize(s: string): string {
  return s
    .normalize('NFC')
    .toLowerCase()
    .replace(/\(주\)|㈜|주식회사|\(유\)|유한회사/g, '')
    .replace(/[\s.\-_*·'’`,:/()[\]]/g, '');
}

// Lists render the same few merchants over and over — memoize the lookup.
const cache = new Map<string, Brand | null>();

export function findBrand(merchant: string): Brand | null {
  const key = merchant.trim();
  if (!key) return null;
  const hit = cache.get(key);
  if (hit !== undefined) return hit;

  const norm = normalize(key);
  const lower = key.toLowerCase();
  let found: Brand | null = null;
  outer: for (const b of BRANDS) {
    for (const m of b.match) {
      if (typeof m === 'string' ? norm.includes(m) : m.test(lower)) {
        found = b;
        break outer;
      }
    }
  }
  if (cache.size > 2000) cache.clear();
  cache.set(key, found);
  return found;
}
